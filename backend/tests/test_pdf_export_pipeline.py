def test_pdf_export_converts_wide_tables_to_sections():
    from app.workspace_export.pipeline.debug_trace import extract_pdf_text

    engine = WorkspaceExportEngine()
    pdf, _, _ = engine.export(MATHCO_TABLE_SAMPLE, ExportFormat.PDF, project_name="MathCo")
    text = extract_pdf_text(pdf)

    assert pdf[:4] == b"%PDF"
    assert "Interview Stage" not in text or "Aptitude Test - Online" in text
    assert "| Communication Test" not in text
    assert "Cultural Alignment" in text
    assert "Stay curious" in text
